// ============================================================
// INKA-BOT — сумма предоплаты, единая точка правды.
// Раньше "200₪" было отдельно зашито в responderPrompt.txt (текст
// клиенту), admin.ts (/счёт) и telegram.ts/payment-reminders.ts (пинги
// мастеру) — при смене суммы для другого мастера пришлось бы искать и
// править все места по отдельности. Теперь одна переменная окружения.
// Env: PAYMENT_DEPOSIT_AMOUNT (число без ₪). По умолчанию 200.
// ============================================================

export function getDepositAmount(): string {
  return (process.env.PAYMENT_DEPOSIT_AMOUNT ?? '').trim() || '200';
}
